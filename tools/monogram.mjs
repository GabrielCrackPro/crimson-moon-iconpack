// Letter-monogram fallback icons.
//
//   node tools/monogram.mjs                     full A-Z 0-9 set -> letters/
//   node tools/monogram.mjs "Bank of America"   one label -> letters/ba.png
//   node tools/monogram.mjs --uncovered [dump]  monograms for every installed
//                                               app the pack does not cover,
//                                               written to src/monograms.json
//   node tools/monogram.mjs --set <pkg> AB      one initials override
//   node tools/monogram.mjs --import list.txt   many overrides at once ("-" = stdin)
//   node tools/monogram.mjs --list              generated vs final initials
//
// A monogram is the same plate and bloom as the rest of the pack, with the
// app's initials drawn in the pack's monoline instead of an object glyph.

import sharp from "sharp";
import { mkdir, writeFile, readFile } from "node:fs/promises";
import path from "node:path";
import { iconSVG } from "../src/render.mjs";
import { LETTERS, LETTER_CHARS, initialsFor, initialsGlyph, initialsId } from "../src/letters.mjs";
import { APPS } from "../src/apps.mjs";
import { parseDump } from "./lib/dump.mjs";
import { loadMonogramState, writeOverrides, INITIALS, OVERRIDES_FILE } from "./lib/monograms.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "letters");
const DENSITIES = [["mdpi", 1], ["hdpi", 1.5], ["xhdpi", 2], ["xxhdpi", 3], ["xxxhdpi", 4]];

const args = process.argv.slice(2);
const flags = new Set(args.filter((a) => a.startsWith("--")));
const rest = args.filter((a) => !a.startsWith("--"));

const renderToBuffer = (glyph, size) =>
  sharp(Buffer.from(iconSVG(glyph, size)), { density: 384 })
    .resize(size, size)
    .png({ compressionLevel: 9 })
    .toBuffer();

async function render(glyph, size, file) {
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, await renderToBuffer(glyph, size));
}

async function contactSheet(entries, file) {
  const cell = 130;
  const cols = 9;
  const rows = Math.ceil(entries.length / cols);
  const tiles = await Promise.all(
    entries.map(async (e, i) => ({
      input: await renderToBuffer(e.glyph, cell - 18),
      left: (i % cols) * cell + 9,
      top: Math.floor(i / cols) * cell + 9,
    })),
  );
  await sharp({
    create: { width: cols * cell, height: rows * cell, channels: 4, background: { r: 8, g: 4, b: 6, alpha: 1 } },
  })
    .composite(tiles)
    .png()
    .toFile(file);
}

async function fullSet() {
  // Overwrites the alphabet files only; any monogram you generated by label stays.
  const entries = LETTER_CHARS.map((ch) => ({ ch, glyph: LETTERS[ch] }));

  for (const { ch } of entries) {
    for (const [d, s] of DENSITIES) {
      await render(LETTERS[ch], Math.round(48 * s), path.join(OUT, "png", d, `${ch}.png`));
    }
    await render(LETTERS[ch], 512, path.join(OUT, `${ch}.png`));
  }
  await contactSheet(entries, path.join(OUT, "sheet.png"));
  console.log(`Wrote ${entries.length} monograms to letters/ (png per density, 512 singles, sheet.png)`);
}

async function single(label) {
  const initials = initialsFor(label);
  const id = initialsId(initials);
  const file = path.join(OUT, `${initials.toLowerCase()}.png`);
  await render(initialsGlyph(initials), 512, file);
  for (const [d, s] of DENSITIES) {
    await render(initialsGlyph(initials), Math.round(48 * s), path.join(OUT, "png", d, `${initials.toLowerCase()}.png`));
  }
  console.log(`"${label}" -> ${initials} (${id}): ${path.relative(ROOT, file)}`);
}

async function uncovered(dumpArg) {
  const dumpPath = dumpArg ? path.resolve(dumpArg) : path.join(ROOT, "device-components.txt");
  let text;
  try {
    text = await readFile(dumpPath, "utf8");
  } catch {
    console.error(`No device dump at ${dumpPath}`);
    console.error("Run tools/sync-components.mjs first, or pass the dump path.");
    process.exit(1);
  }

  const device = parseDump(text);
  const covered = new Set(APPS.flatMap((a) => a.pkgs.map((p) => p.split("/")[0])));
  const out = {};
  const skipped = [];

  for (const [pkg, acts] of device) {
    if (covered.has(pkg)) continue;
    if (!acts.length) {
      skipped.push(pkg);
      continue;
    }
    const label = pkg.split(".").pop();
    out[pkg] = { initials: initialsFor(label), component: `${pkg}/${acts[0]}` };
  }

  await writeFile(path.join(ROOT, "src/monograms.json"), JSON.stringify(out, null, 2) + "\n");
  console.log(`${Object.keys(out).length} uncovered apps get a monogram.`);
  for (const [pkg, v] of Object.entries(out)) console.log(`  ${v.initials.padEnd(3)} ${pkg}`);
  if (skipped.length) {
    console.log(`\n${skipped.length} package(s) had no launcher activity and were skipped:`);
    for (const p of skipped) console.log(`  ${p}`);
  }
  console.log("\nRebuild: npm run build && npm run check");
}

async function setInitials(pkg, initials) {
  const value = String(initials ?? "").toUpperCase();
  if (!pkg || !INITIALS.test(value)) {
    console.error('Usage: node tools/monogram.mjs --set com.package "AB"   (1-2 letters or digits)');
    process.exit(1);
  }

  const state = await loadMonogramState(ROOT);
  const base = state.base[pkg];
  if (!base) {
    console.error(`${pkg} has no monogram yet.`);
    console.error("Run: node tools/monogram.mjs --uncovered   (needs a device dump)");
    process.exit(1);
  }
  if (base.initials === value) {
    console.warn(`note: "${value}" is already the generated initials — the override changes nothing.`);
  }

  state.overrides[pkg] = value;
  await writeOverrides(ROOT, state.overrides);
  console.log(`${pkg}: ${base.initials} -> ${value}  (${OVERRIDES_FILE})`);
  console.log("Rebuild: npm run build && npm run check");
}

async function unsetInitials(pkg) {
  const state = await loadMonogramState(ROOT);
  if (!pkg || !(pkg in state.overrides)) {
    console.error(`No initials override for "${pkg ?? ""}".`);
    console.error(`Overrides live in ${OVERRIDES_FILE}; see --list.`);
    process.exit(1);
  }
  delete state.overrides[pkg];
  await writeOverrides(ROOT, state.overrides);
  console.log(`${pkg}: override removed, back to ${state.base[pkg]?.initials ?? "generated"}`);
}

async function readStdin() {
  if (process.stdin.isTTY) {
    console.error('No list on stdin. Pipe one in: cat list.txt | npm run monogram -- --import -');
    process.exit(1);
  }
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  return Buffer.concat(chunks).toString("utf8");
}

// Bulk import: one "package INITIALS" per line. Accepts spaces, tabs, commas,
// colons or equals between the two fields, and # comments. All-or-nothing: if
// any line is invalid nothing is written, so a typo can't leave a half state.
async function importList(file) {
  if (!file) {
    console.error("Usage: node tools/monogram.mjs --import overrides.txt   (or --import - for stdin)");
    process.exit(1);
  }

  let text;
  try {
    text = file === "-" ? await readStdin() : await readFile(path.resolve(file), "utf8");
  } catch {
    console.error(`Cannot read ${file}`);
    process.exit(1);
  }

  const state = await loadMonogramState(ROOT);
  const next = { ...state.overrides };
  const errors = [];
  let seen = 0;

  text.split(/\r?\n/).forEach((rawLine, index) => {
    // A trailing "# note" is allowed so lists read like a table.
    const line = rawLine.split("#")[0].trim();
    if (!line || line.startsWith("//")) return;
    seen++;

    const parts = line.replace(/[=,:]/g, " ").trim().split(/\s+/);
    if (parts.length !== 2) {
      errors.push(`line ${index + 1}: expected "package INITIALS", got "${line}"`);
      return;
    }

    const [pkg, rawInitials] = parts;
    const initials = rawInitials.toUpperCase();
    if (!INITIALS.test(initials)) {
      errors.push(`line ${index + 1}: "${rawInitials}" is not 1-2 letters or digits`);
      return;
    }
    if (!state.base[pkg]) {
      errors.push(`line ${index + 1}: no monogram for ${pkg} (run: node tools/monogram.mjs --uncovered)`);
      return;
    }
    next[pkg] = initials;
  });

  if (!seen) {
    console.error("No entries found — expected lines like: com.example.app EA");
    process.exit(1);
  }
  if (errors.length) {
    console.error(`${errors.length} problem(s) — nothing written:\n`);
    for (const e of errors) console.error(`  ✗ ${e}`);
    process.exit(1);
  }

  await writeOverrides(ROOT, next);
  console.log(`${seen} line(s) imported, ${Object.keys(next).length} override(s) active in ${OVERRIDES_FILE}.`);
  console.log("Rebuild: npm run build && npm run check");
}

async function listMonograms() {
  const { merged } = await loadMonogramState(ROOT);
  const pkgs = Object.keys(merged).sort();
  if (!pkgs.length) {
    console.log("No monograms yet — run: node tools/monogram.mjs --uncovered");
    return;
  }
  console.log(`${"PACKAGE".padEnd(40)} ${"AUTO".padEnd(5)} ${"FINAL".padEnd(6)} SOURCE`);
  for (const pkg of pkgs) {
    const v = merged[pkg];
    console.log(
      `${pkg.padEnd(40)} ${String(v.generated).padEnd(5)} ${v.initials.padEnd(6)} ${v.override ? "override" : "generated"}`,
    );
  }
  console.log(`\n${pkgs.length} monogram(s). Override with: node tools/monogram.mjs --set <package> "AB"`);
}

if (flags.has("--import")) {
  await importList(rest[0]);
} else if (flags.has("--set")) {
  await setInitials(rest[0], rest[1]);
} else if (flags.has("--unset")) {
  await unsetInitials(rest[0]);
} else if (flags.has("--list")) {
  await listMonograms();
} else if (flags.has("--uncovered")) {
  await uncovered(rest[0]);
} else if (rest.length) {
  await single(rest.join(" "));
} else {
  await fullSet();
}
